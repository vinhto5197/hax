#!/usr/bin/env bash
# The project's live state, printed from its sources, never written by hand:
# main's head and latest commits, uncommitted files, open PRs, the feature
# ledger, the nightly queue, the digest and retro marks, the week's retro
# tally, the explorer's last run. Then the ordered next list, the one part
# that is a decision: the "### Next" section of the backlog's START HERE,
# kept by the controller whenever the maintainer's decisions change it.
# A missing source is named, never guessed. The due hook attaches this to the
# day's first prompt; any answer about "what's next" starts from it.
#
#   scripts/state.sh          state, then the next list
#   scripts/state.sh --next   the next list only
#
# DUE_TODAY (YYYY-MM-DD) pins the clock for tests.
set -u
root=${CLAUDE_PROJECT_DIR:-$(cd "$(dirname "$0")/.." && pwd)}
local_dir=$root/local
backlog=$local_dir/DEV_BACKLOG.local.md

next_list() {
  if [ ! -f "$backlog" ]; then echo "next list: DEV_BACKLOG.local.md missing"; return; fi
  local section
  section=$(awk '/^### Next/ {on=1; print; next} on && /^##/ {exit} on' "$backlog")
  if [ -z "$section" ]; then echo "next list: no '### Next' section in DEV_BACKLOG.local.md"; else echo "$section"; fi
}

if [ "${1:-}" = --next ]; then next_list; exit 0; fi

today=${DUE_TODAY:-$(date +%F)}
week=$(python3 -c "import datetime,sys;y,w,_=datetime.date.fromisoformat(sys.argv[1]).isocalendar();print(f'{y}-W{w:02d}')" "$today")

echo "### State ($today, generated by scripts/state.sh)"
head=$(git -C "$root" rev-parse --short main 2>/dev/null) || head="?"
echo "- main at $head; latest: $(git -C "$root" log -3 --format='%h %s' main 2>/dev/null | sed 's/$/;/' | tr '\n' ' ')"
echo "- uncommitted files: $(git -C "$root" status --short 2>/dev/null | wc -l | tr -d ' ')"
# gh is the one network call; perl's alarm bounds it because macOS has no timeout(1).
prs=$(cd "$root" && perl -e 'alarm 8; exec @ARGV' gh pr list --state open --limit 100 --json headRefName \
  -q '[.[].headRefName] | "\(map(select(startswith("routine/"))) | length) routine, \(map(select(startswith("journey/"))) | length) journey, \(map(select(startswith("feat/"))) | length) feature, \(length) in all"' 2>/dev/null) \
  || prs="unknown (gh failed)"
echo "- open PRs: $prs"

if [ -f "$local_dir/features.json" ]; then
  echo "- features: $(jq -r '[.features[] | "\(.id): \(.state)"] | join("; ")' "$local_dir/features.json" 2>/dev/null)"
else
  echo "- features: features.json missing"
fi

if [ -f "$local_dir/routine-queue.md" ]; then
  ids=$(grep -oE '^- id: [A-Za-z0-9._-]+' "$local_dir/routine-queue.md" | sed 's/^- id: //')
  n=$(printf '%s\n' "$ids" | grep -c . || true)
  echo "- nightly queue: $n items ($(printf '%s\n' "$ids" | paste -sd, - | sed 's/,/, /g'))"
else
  echo "- nightly queue: routine-queue.md missing"
fi

marker=$local_dir/routine-marker.json
if [ -f "$marker" ]; then
  echo "- marks: digest $(jq -r '.last_digest_date // "never"' "$marker"), retro $(jq -r '.last_retro_week // "never"' "$marker")"
else
  echo "- marks: routine-marker.json missing"
fi

retro=$local_dir/retro/$week.md
if [ -f "$retro" ]; then
  tally=$(grep -oE '^- [0-9]{4}-[0-9]{2}-[0-9]{2} \[[a-z-]+\]' "$retro" | sed -E 's/.*\[([a-z-]+)\]/\1/' | sort | uniq -c | sort -rn \
    | awk '{printf "%s%s %d%s", (NR>1?", ":""), $2, $1, ($1>=2?" (recurring)":"")}')
  echo "- retro $week: ${tally:-no lines yet}"
else
  echo "- retro $week: no week file yet"
fi

status=$local_dir/explorer/.status.json
if [ -f "$status" ]; then
  echo "- $(jq -r '"explorer \(.week): \(.state) (\(.persona // "?"))\(if .notes then ", notes " + .notes else "" end)"' "$status" 2>/dev/null)"
else
  echo "- explorer: no run yet"
fi

echo
next_list
